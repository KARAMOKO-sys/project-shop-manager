<?php

namespace App\Models;

use App\Enums\StockMovementType;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\MorphTo;

/**
 * Immutable line of the stock ledger: every quantity change is explained here.
 */
class StockMovement extends Model
{
    protected $fillable = ['shop_id', 'product_id', 'warehouse_id', 'type', 'quantity', 'warehouse_quantity_after', 'reference', 'source_type', 'source_id', 'note', 'user_id'];

    protected $casts = [
        'type' => StockMovementType::class,
    ];

    public function product(): BelongsTo
    {
        return $this->belongsTo(Product::class);
    }

    public function warehouse(): BelongsTo
    {
        return $this->belongsTo(Warehouse::class);
    }

    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function source(): MorphTo
    {
        return $this->morphTo();
    }
}
